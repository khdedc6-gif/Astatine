    NULLIF(trim(app_user.email), ''),
    (
      SELECT auth_user.email
      FROM auth.users AS auth_user
      WHERE auth_user.id = app_user.id
    ),
    'user_' || app_user.id::text || '@no-email.invalid'
  )
WHERE app_user.username IS NULL
   OR trim(app_user.username) = ''
   OR app_user.email IS NULL
   OR trim(app_user.email) = '';

