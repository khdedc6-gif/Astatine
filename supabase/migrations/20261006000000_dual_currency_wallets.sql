CREATE OR REPLACE FUNCTION public.award_assignment_coin_reward(
  p_assignment_id uuid
)
RETURNS numeric
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_wallet public.user_wallets%ROWTYPE;
  v_reward numeric(18, 4);
  v_teacher_id uuid;
  v_teacher_wallet public.user_wallets%ROWTYPE;
  v_teacher_balance_before numeric(18, 4);
  v_teacher_balance_after numeric(18, 4);
  v_balance_before numeric(18, 4);
  v_balance_after numeric(18, 4);
  v_submission public.assignment_submissions%ROWTYPE;
  v_total_points numeric;
  v_earned_points numeric;
  v_score numeric;
  v_passing_score numeric;
  v_already_awarded boolean;
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Authentication required';
  END IF;

  SELECT submission.*
  INTO v_submission
  FROM public.assignment_submissions AS submission
  WHERE submission.assignment_id = p_assignment_id
    AND submission.student_id = v_user_id
    AND upper(submission.status) = 'SUBMITTED'
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Submitted quiz not found for current user';
  END IF;

  SELECT assignment.coin_reward,
         COALESCE(assignment.passing_score, 0),
         assignment.teacher_id
  INTO v_reward, v_passing_score, v_teacher_id
  FROM public.assignments AS assignment
  WHERE assignment.id = p_assignment_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Quiz not found';
  END IF;

  SELECT COALESCE(sum(question.question_points), 0),
         COALESCE(sum(
           CASE
             WHEN upper(trim(v_submission.answers ->> question.id::text))
                  = chr(65 + question.correct_option::integer)
             THEN question.question_points
             ELSE 0
           END
         ), 0)
  INTO v_total_points, v_earned_points
  FROM public.questions AS question
  WHERE question.assignment_id = p_assignment_id;

  IF v_total_points <= 0 THEN
    RAISE EXCEPTION 'Quiz has no scorable questions';
  END IF;

  v_score := v_earned_points * 10 / v_total_points;
  IF v_score < v_passing_score OR v_reward <= 0 THEN
    SELECT isotope_coin_balance
    INTO v_balance_before
    FROM public.user_wallets
    WHERE user_id = v_user_id;
    RETURN COALESCE(v_balance_before, 0);
  END IF;

  INSERT INTO public.user_wallets (user_id)
  VALUES (v_user_id)
  ON CONFLICT (user_id) DO NOTHING;

  SELECT *
  INTO v_wallet
  FROM public.user_wallets
  WHERE user_id = v_user_id
  FOR UPDATE;

  IF v_wallet.wallet_status <> 'ACTIVE' THEN
    RAISE EXCEPTION 'Wallet is not active';
  END IF;

  SELECT EXISTS (
    SELECT 1
    FROM public.wallet_transactions AS ledger_row
    WHERE ledger_row.user_id = v_user_id
      AND ledger_row.reference_type = 'ASSIGNMENT'
      AND ledger_row.reference_id = p_assignment_id::text
      AND ledger_row.currency = 'ISOTOPE'
      AND ledger_row.transaction_type = 'REWARD'
      AND ledger_row.status = 'SUCCESS'
  )
  INTO v_already_awarded;

  IF v_already_awarded THEN
    RETURN v_wallet.isotope_coin_balance;
  END IF;

  v_balance_before := v_wallet.isotope_coin_balance;
  v_balance_after := v_balance_before + v_reward;

  UPDATE public.user_wallets
  SET isotope_coin_balance = v_balance_after,
      version = version + 1
  WHERE user_id = v_user_id;

  INSERT INTO public.wallet_transactions (
    transaction_code, user_id, currency, amount, balance_before,
    balance_after, type, transaction_type, reference_type, reference_id,
    description, status
  )
  VALUES (
    'QUIZ-' || md5(p_assignment_id::text || v_user_id::text),
    v_user_id,
    'ISOTOPE',
    v_reward,
    v_balance_before,
    v_balance_after,
    'REWARD',
    'REWARD',
    'ASSIGNMENT',
    p_assignment_id::text,
    'Coin reward for completing a quiz',
    'SUCCESS'
  )
  ON CONFLICT DO NOTHING;

  IF v_teacher_id IS NOT NULL AND v_teacher_id <> v_user_id THEN
    INSERT INTO public.user_wallets (user_id)
    VALUES (v_teacher_id)
    ON CONFLICT (user_id) DO NOTHING;

    SELECT *
    INTO v_teacher_wallet
    FROM public.user_wallets
    WHERE user_id = v_teacher_id
    FOR UPDATE;

    IF v_teacher_wallet.wallet_status = 'ACTIVE'
       AND NOT EXISTS (
         SELECT 1
         FROM public.wallet_transactions AS teacher_transaction
         WHERE teacher_transaction.user_id = v_teacher_id
           AND teacher_transaction.reference_type = 'ASSIGNMENT'
           AND teacher_transaction.reference_id =
             p_assignment_id::text || ':' || v_user_id::text
           AND teacher_transaction.currency = 'ISOTOPE'
           AND teacher_transaction.transaction_type = 'REWARD'
           AND teacher_transaction.status = 'SUCCESS'
       ) THEN
      v_teacher_balance_before := v_teacher_wallet.isotope_coin_balance;
      v_teacher_balance_after := v_teacher_balance_before + 10;

      UPDATE public.user_wallets
      SET isotope_coin_balance = v_teacher_balance_after,
          version = version + 1
      WHERE user_id = v_teacher_id;

      INSERT INTO public.wallet_transactions (
        transaction_code, user_id, currency, amount, balance_before,
        balance_after, type, transaction_type, reference_type, reference_id,
        description, status
      )
      VALUES (
        'QUIZ-TEACHER-' || md5(p_assignment_id::text || v_user_id::text),
        v_teacher_id,
        'ISOTOPE',
        10,
        v_teacher_balance_before,
        v_teacher_balance_after,
        'REWARD',
        'REWARD',
        'ASSIGNMENT',
        p_assignment_id::text || ':' || v_user_id::text,
        'Teacher Coin incentive for student quiz completion',
        'SUCCESS'
      )
      ON CONFLICT DO NOTHING;
    END IF;
  END IF;

  RETURN v_balance_after;
END;
$$;

