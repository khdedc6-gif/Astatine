CREATE TABLE IF NOT EXISTS public.user_wallets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL UNIQUE
    REFERENCES public.users(id) ON DELETE CASCADE,
  isotope_coin_balance numeric(18, 4) NOT NULL DEFAULT 0
    CHECK (isotope_coin_balance >= 0),
  isotope_coin_frozen numeric(18, 4) NOT NULL DEFAULT 0
    CHECK (isotope_coin_frozen >= 0),
  ast_balance numeric(18, 4) NOT NULL DEFAULT 0
    CHECK (ast_balance >= 0),
  ast_frozen numeric(18, 4) NOT NULL DEFAULT 0
    CHECK (ast_frozen >= 0),
  wallet_status varchar(20) NOT NULL DEFAULT 'ACTIVE'
    CHECK (wallet_status IN ('ACTIVE', 'LOCKED', 'FROZEN')),
  version integer NOT NULL DEFAULT 0 CHECK (version >= 0),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT user_wallets_coin_frozen_within_balance
    CHECK (isotope_coin_frozen <= isotope_coin_balance),
  CONSTRAINT user_wallets_ast_frozen_within_balance
    CHECK (ast_frozen <= ast_balance)
);

CREATE TABLE IF NOT EXISTS public.wallet_transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_code varchar(64) NOT NULL UNIQUE
    DEFAULT gen_random_uuid()::text,
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  currency varchar(10) NOT NULL REFERENCES public.currencies(code),
  amount numeric(18, 4) NOT NULL CHECK (amount <> 0),
  balance_before numeric(18, 4) NOT NULL CHECK (balance_before >= 0),
  balance_after numeric(18, 4) NOT NULL CHECK (balance_after >= 0),
  type varchar(30) NOT NULL DEFAULT 'REWARD',
  transaction_type varchar(30) NOT NULL CHECK (
    transaction_type IN (
      'TOPUP', 'REWARD', 'EARN_AST', 'SPEND_AST', 'SPEND_ISOTOPE',
      'ADMIN_ADJUST', 'CONVERT'
    )
  ),
  reference_type varchar(50),
  reference_id varchar(100),
  description text,
  status varchar(20) NOT NULL DEFAULT 'SUCCESS'
    CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'CANCELLED')),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT wallet_transactions_balance_delta
    CHECK (balance_after = balance_before + amount)
);

CREATE INDEX IF NOT EXISTS wallet_transactions_user_created_idx
  ON public.wallet_transactions (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS wallet_transactions_created_idx
  ON public.wallet_transactions (created_at DESC);
CREATE INDEX IF NOT EXISTS wallet_transactions_reference_idx
  ON public.wallet_transactions (reference_type, reference_id);
CREATE UNIQUE INDEX IF NOT EXISTS wallet_transactions_unique_assignment_reward
  ON public.wallet_transactions (user_id, reference_id, currency)
  WHERE transaction_type = 'REWARD'
    AND reference_type = 'ASSIGNMENT'
    AND status = 'SUCCESS';

CREATE TABLE IF NOT EXISTS public.exchange_rates (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_currency varchar(10) NOT NULL REFERENCES public.currencies(code),
  to_currency varchar(10) NOT NULL REFERENCES public.currencies(code),
  rate numeric(18, 6) NOT NULL CHECK (rate > 0),
  min_amount numeric(18, 4) NOT NULL DEFAULT 1 CHECK (min_amount > 0),
  is_enabled boolean NOT NULL DEFAULT true,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT exchange_rates_distinct_currencies
    CHECK (from_currency <> to_currency),
  CONSTRAINT exchange_rates_pair_unique UNIQUE (from_currency, to_currency)
);

CREATE TABLE IF NOT EXISTS public.topup_orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_code varchar(64) NOT NULL UNIQUE,
  user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
  fiat_amount numeric(18, 2) NOT NULL CHECK (fiat_amount > 0),
  fiat_currency varchar(5) NOT NULL DEFAULT 'VND',
  isotope_amount numeric(18, 4) NOT NULL CHECK (isotope_amount > 0),
  payment_method varchar(50)
    CHECK (payment_method IS NULL OR payment_method IN (
      'MOMO', 'BANK_TRANSFER', 'IN_APP_PURCHASE', 'CARD'
    )),
  payment_status varchar(20) NOT NULL DEFAULT 'PENDING'
    CHECK (payment_status IN ('PENDING', 'COMPLETED', 'FAILED', 'REFUNDED')),
  transaction_payload jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  CONSTRAINT topup_orders_completed_timestamp
    CHECK (payment_status <> 'COMPLETED' OR completed_at IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS topup_orders_user_created_idx
  ON public.topup_orders (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS topup_orders_status_created_idx
  ON public.topup_orders (payment_status, created_at DESC);

