CREATE OR REPLACE FUNCTION public.create_app_user_for_auth_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  base_username text;
BEGIN
  base_username := COALESCE(
    NULLIF(NEW.raw_user_meta_data ->> 'username', ''),
    'user'
  );

  INSERT INTO public.users (id, username, email, full_name)
  VALUES (
    NEW.id,
    left(base_username, 13) || '_' || replace(NEW.id::text, '-', ''),
    COALESCE(NEW.email, 'user_' || NEW.id::text || '@no-email.invalid'),
    NULLIF(NEW.raw_user_meta_data ->> 'full_name', '')
  )
  ON CONFLICT (id) DO UPDATE
  SET email = EXCLUDED.email;

  INSERT INTO public.user_wallets (user_id)
  VALUES (NEW.id)
  ON CONFLICT (user_id) DO NOTHING;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created_wallet ON auth.users;
CREATE TRIGGER on_auth_user_created_wallet
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.create_app_user_for_auth_user();

