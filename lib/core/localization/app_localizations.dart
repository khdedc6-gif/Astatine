  static String t(
    String key, {
    bool isVietnamese = true,
    String? languageCode,
    Map<String, Object?> arguments = const {},
  }) {
    final parts = key.split('.');
    final locale = switch (languageCode ?? (isVietnamese ? 'vi' : 'en')) {
      'vi' => _vi,
      'zh' => _zh,
      _ => _en,
    };
    var value = locale[parts.first]?[parts.skip(1).join('.')];
    value ??= _en[parts.first]?[parts.skip(1).join('.')];
    value ??= key;
    for (final entry in arguments.entries) {
      value = value!.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return value!;
  }
