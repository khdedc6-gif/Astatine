  static String translateInline(String text, {required String languageCode}) {
    if (languageCode != 'zh') return text;
    final translation = _zhInline[text];
    if (translation != null) return translation;

    for (final entry in _zhInline.entries) {
      final placeholders = RegExp(r'\{([^}]+)\}').allMatches(entry.key);
      if (placeholders.isEmpty) continue;

      final pattern = StringBuffer('^');
      var cursor = 0;
      for (final placeholder in placeholders) {
        pattern
          ..write(RegExp.escape(entry.key.substring(cursor, placeholder.start)))
          ..write('(.*?)');
        cursor = placeholder.end;
      }
      pattern.write(RegExp.escape(entry.key.substring(cursor)));
      final match = RegExp('${pattern.toString()}\$').firstMatch(text);
      if (match == null) continue;

      var result = entry.value;
      var group = 1;
      for (final placeholder in placeholders) {
        result = result.replaceFirst(
          entry.key.substring(placeholder.start, placeholder.end),
          match.group(group++) ?? '',
        );
      }
      return result;
    }
